const pick = (pool, n) => pool[((n % pool.length) + pool.length) % pool.length];

const data = {};
const counts = { 대길: 0, 길: 0, 평: 0, 기복: 0, 주의: 0 };
for (let s = 1; s <= 8; s++) for (let j = 1; j <= 6; j++) for (let h = 1; h <= 3; h++) {
  const seed = s * 100 + j * 10 + h;
  const g = GRADES[GRADE_PATTERN[seed % GRADE_PATTERN.length]];
  counts[g]++;
  const chong = pick(INTRO, seed) + ' ' + pick(FLOW[g], seed * 3 + 7) + ' ' + pick(DEPTH[g], seed * 5 + 1) + ' ' + pick(ADVICE[g], seed * 7 + 2);
  const months = [];
  for (let m = 1; m <= 12; m++) months.push({
    m, label: pick(M_LABEL[g], seed + m * 5),
    text: pick(M_SIT[g], seed * 7 + m * 13) + ' ' + pick(M_ADV[g], seed * 11 + m * 17),
  });
  data[`${s}${j}${h}`] = {
    sang: s, jung: j, ha: h, grade: g, summary: pick(SUMMARY[g], seed),
    chong,
    jaemul: pick(JAEMUL[g], seed * 3 + 1), geongang: pick(GEONGANG[g], seed * 5 + 2),
    aejeong: pick(AEJEONG[g], seed * 7 + 3), jikeop: pick(JIKEOP[g], seed * 9 + 4),
    advice: pick(ADVICE[g], seed * 13 + 5),
    months,
  };
}

