const pick = (pool, n) => pool[((n % pool.length) + pool.length) % pool.length];

const data = {};
let counts = { 대길: 0, 길: 0, 평: 0, 기복: 0, 주의: 0 };
for (let s = 1; s <= 8; s++) for (let j = 1; j <= 6; j++) for (let h = 1; h <= 3; h++) {
  const seed = s * 100 + j * 10 + h;   // 괘마다 고유
  const grade = GRADES[GRADE_PATTERN[seed % GRADE_PATTERN.length]];
  counts[grade]++;
  const chong = pick(INTRO, seed) + ' ' + pick(FLOW[grade], seed * 3 + 7) + ' ' + pick(ADVICE[grade], seed * 5 + 2);
  const months = [];
  for (let m = 1; m <= 12; m++) months.push(m + '월. ' + pick(MONTHS[grade], seed * 13 + m * 37));
  data[`${s}${j}${h}`] = { sang: s, jung: j, ha: h, grade, summary: pick(SUMMARY[grade], seed), chong, months };
}

