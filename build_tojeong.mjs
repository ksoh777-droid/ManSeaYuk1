const pick = (pool, n) => pool[((n % pool.length) + pool.length) % pool.length];
function pick3(pool, seed) {
  const a = pick(pool, seed), b = pick(pool, seed * 7 + 3), c = pick(pool, seed * 13 + 5);
  const set = [a]; if (!set.includes(b)) set.push(b); if (!set.includes(c)) set.push(c);
  let k = seed; while (set.length < 3) { const x = pick(pool, ++k * 3 + 1); if (!set.includes(x)) set.push(x); }
  return set;
}

